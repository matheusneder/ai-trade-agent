"""Claude API calls: structured output, research with web search, cost and budget.

* **Budget:** the day's (UTC) spending is compared with the ``budget.daily_usd`` cap; once
  the cap is reached, nothing is called (``BudgetExceededError``). By default the check runs
  before every call; a research cycle checks once at its start instead
  (``budget_per_call=False``), so it never pays for the web step and then loses the reading.
* **Cost:** every response is recorded in the ``UsageLedger`` (tokens, cache, searches and
  US$) **before** the output is validated, so invalid responses are accounted for too.
* **Structured output:** ``output_config.format`` with the schema generated by the SDK
  (``transform_schema``) and local validation with pydantic.
* **Research:** server tools ``web_search``/``web_fetch`` with ``max_uses``;
  ``pause_turn`` is resumed up to ``max_continuations`` times.
* The *system prompt* is marked for *prompt caching* (stable prefix).
"""

import asyncio
import math
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from decimal import Decimal
from email.utils import parsedate_to_datetime
from typing import Any, Protocol

import anthropic
import httpx2
import structlog
from anthropic.types import Message, Usage
from opentelemetry import trace
from opentelemetry.trace import SpanKind
from pydantic import BaseModel, ValidationError

from trade_agent import metrics, tracing
from trade_agent.research.config import ModelPrice, PricingConfig, ResearchConfig

log = structlog.get_logger(__name__)

MILLION = Decimal(1_000_000)
DEFAULT_API_URL = "https://api.anthropic.com"
"""Used in the spans when the client has no ``base_url`` (test doubles)."""


def uncertain_api_error(error: anthropic.APIError) -> bool:
    """Distinguish rejected/pre-send attempts from an unobserved processing result.

    The SDK wraps connect, read and write failures in APIConnectionError. Only its
    concrete transport cause can establish that no request was sent. HTTP 408 and
    server errors remain uncertain; a local usage row is not proof of non-billing.
    """
    if isinstance(error, anthropic.APIStatusError):
        return not (400 <= error.status_code < 500 and error.status_code != 408)
    return not isinstance(
        error.__cause__, (httpx2.ConnectError, httpx2.ConnectTimeout, httpx2.PoolTimeout)
    )


class LlmError(Exception):
    """Analyst failure; the caller degrades to pure TA."""


def retry_delay(error: anthropic.APIError, now: datetime) -> float | None:
    """One retry, only for explicit rate rejection or proven pre-send failure."""
    if isinstance(error, anthropic.APIStatusError):
        if error.status_code != 429:
            return None
        value = error.response.headers.get("retry-after", "1")
        try:
            delay = float(value)
        except ValueError:
            try:
                delay = (parsedate_to_datetime(value) - now).total_seconds()
            except (ValueError, TypeError, OverflowError):
                delay = 1.0
        return max(0.0, delay) if math.isfinite(delay) else 1.0
    return 1.0 if not uncertain_api_error(error) else None


class BudgetExceededError(LlmError):
    pass


class LlmOutputError(LlmError):
    """Response with no usable output (refusal, truncation, JSON outside the schema)."""


@dataclass(frozen=True, slots=True)
class LlmUsage:
    purpose: str
    model: str
    input_tokens: int
    output_tokens: int
    cache_creation_input_tokens: int
    cache_read_input_tokens: int
    web_search_requests: int
    web_fetch_requests: int
    cost_usd: Decimal
    at: datetime


class UsageLedger(Protocol):
    async def spent_since(self, start: datetime) -> Decimal: ...

    async def record(self, usage: LlmUsage) -> None: ...


class MemoryLedger:
    """In-memory ledger (offline evaluation and tests)."""

    def __init__(self) -> None:
        self.usages: list[LlmUsage] = []

    async def spent_since(self, start: datetime) -> Decimal:
        return sum((u.cost_usd for u in self.usages if u.at >= start), Decimal(0))

    async def record(self, usage: LlmUsage) -> None:
        self.usages.append(usage)


class TrackingLedger:
    """Forwards to the main ledger and adds up the cost of one cycle's calls."""

    def __init__(self, inner: UsageLedger) -> None:
        self._inner = inner
        self.total = Decimal(0)

    async def spent_since(self, start: datetime) -> Decimal:
        return await self._inner.spent_since(start)

    async def record(self, usage: LlmUsage) -> None:
        self.total += usage.cost_usd
        await self._inner.record(usage)


def usage_cost(usage: Usage, price: ModelPrice, pricing: PricingConfig) -> Decimal:
    """Cost in US$ of a response (*thinking* tokens are already in ``output_tokens``)."""
    cached_write = Decimal(usage.cache_creation_input_tokens or 0)
    cached_read = Decimal(usage.cache_read_input_tokens or 0)
    searches = usage.server_tool_use.web_search_requests if usage.server_tool_use else 0
    return (
        Decimal(usage.input_tokens) * price.input
        + Decimal(usage.output_tokens) * price.output
        + cached_write * price.input * pricing.cache_write_multiplier
        + cached_read * price.input * pricing.cache_read_multiplier
    ) / MILLION + Decimal(searches) * pricing.web_search_per_1000 / 1000


@dataclass(frozen=True, slots=True)
class ResearchFindings:
    text: str
    sources: tuple[str, ...]
    """URLs cited in the text or read with ``web_fetch``."""


def _findings(blocks: Sequence[Any]) -> ResearchFindings:
    texts: list[str] = []
    sources: list[str] = []
    for block in blocks:
        if block.type == "text":
            texts.append(block.text)
            sources.extend(url for c in block.citations or () if (url := getattr(c, "url", None)))
        elif block.type == "web_fetch_tool_result":
            url = getattr(block.content, "url", None)
            if url:
                sources.append(url)
    return ResearchFindings("".join(texts).strip(), tuple(dict.fromkeys(sources)))


class ClaudeClient:
    def __init__(
        self,
        client: anthropic.AsyncAnthropic,
        config: ResearchConfig,
        ledger: UsageLedger,
        clock: Callable[[], datetime] = lambda: datetime.now(UTC),
        *,
        budget_per_call: bool = True,
        cycle_allowance: Decimal | None = None,
    ) -> None:
        self._client = client.with_options(max_retries=0) if cycle_allowance is not None else client
        self._config = config
        self._ledger = ledger
        self._clock = clock
        self._budget_per_call = budget_per_call
        self._cycle_allowance = cycle_allowance
        self._cycle_cost = Decimal(0)
        self._inflight = False
        self._uncertain_charge = False
        self.budget_notes: list[str] = []

    @property
    def uncertain_charge(self) -> bool:
        return self._inflight or self._uncertain_charge

    async def _fit_budget(self, purpose: str, params: dict[str, Any]) -> None:
        if self._cycle_allowance is None:
            return
        if self.uncertain_charge:
            raise BudgetExceededError("cobrança anterior incerta; ciclo interrompido")
        if params.get("tools"):
            raise BudgetExceededError("ferramentas web sem custo máximo previsível")
        count_params = {
            k: params[k] for k in ("model", "messages", "system", "output_config") if k in params
        }
        try:
            count = await self._client.messages.count_tokens(
                **count_params, timeout=self._config.models.timeout_s
            )
        except anthropic.APIError as exc:
            raise LlmError("contagem de tokens indisponível; chamada omitida") from exc
        price = self._config.pricing.models[params["model"]]
        # Token counting is an estimate; reserve headroom and assume uncached writes.
        input_cost = (Decimal(count.input_tokens) * Decimal("1.1") + 1024) * price.input
        input_cost *= max(Decimal(1), self._config.pricing.cache_write_multiplier) / MILLION
        remaining = self._cycle_allowance - self._cycle_cost
        if purpose == "triage":
            remaining = min(remaining, self._cycle_allowance / 4)
        affordable = int(max(Decimal(0), remaining - input_cost) * MILLION / price.output)
        if affordable < 1024:
            raise BudgetExceededError("saldo insuficiente para uma resposta útil")
        if affordable < params["max_tokens"]:
            params["max_tokens"] = affordable
            self.budget_notes.append(f"{purpose}: saída reduzida para {affordable} tokens")

    async def check_budget(self) -> None:
        """Raises ``BudgetExceededError`` if the day's spending already reached the cap."""
        now = self._clock()
        day_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
        spent = await self._ledger.spent_since(day_start)
        if spent >= self._config.budget.daily_usd:
            raise BudgetExceededError(
                f"orçamento diário do LLM atingido (US$ {spent:.2f} de "
                f"US$ {self._config.budget.daily_usd})"
            )

    async def _record(self, purpose: str, model: str, response: Message) -> None:
        usage = response.usage
        server = usage.server_tool_use
        record = LlmUsage(
            purpose=purpose,
            model=model,
            input_tokens=usage.input_tokens,
            output_tokens=usage.output_tokens,
            cache_creation_input_tokens=usage.cache_creation_input_tokens or 0,
            cache_read_input_tokens=usage.cache_read_input_tokens or 0,
            web_search_requests=server.web_search_requests if server else 0,
            web_fetch_requests=(server.web_fetch_requests or 0) if server else 0,
            cost_usd=usage_cost(usage, self._config.pricing.models[model], self._config.pricing),
            at=self._clock(),
        )
        await self._ledger.record(record)
        self._cycle_cost += record.cost_usd
        self._inflight = False
        metrics.record_llm(
            model=model,
            purpose=purpose,
            cost_usd=record.cost_usd,
            input_tokens=record.input_tokens,
            output_tokens=record.output_tokens,
        )
        current = trace.get_current_span()
        current.set_attribute("gen_ai.response.finish_reasons", [str(response.stop_reason)])
        # GenAI convention: input_tokens includes the cached tokens, which Anthropic reports
        # apart. SigNoz (collector v0.144.13+) subtracts cache_read and cache_creation from it
        # to price each bucket: without the sum, it would bill part of the input twice as cache.
        current.set_attribute(
            "gen_ai.usage.input_tokens",
            record.input_tokens
            + record.cache_read_input_tokens
            + record.cache_creation_input_tokens,
        )
        current.set_attribute("gen_ai.usage.output_tokens", record.output_tokens)
        current.set_attribute(
            "gen_ai.usage.cache_read.input_tokens", record.cache_read_input_tokens
        )
        current.set_attribute(
            "gen_ai.usage.cache_creation.input_tokens", record.cache_creation_input_tokens
        )
        current.set_attribute("trade_agent.web_searches", record.web_search_requests)
        current.set_attribute("trade_agent.cost_usd", str(record.cost_usd))
        log.debug(
            "llm.response",
            purpose=purpose,
            model=model,
            stop_reason=response.stop_reason,
            input_tokens=record.input_tokens,
            output_tokens=record.output_tokens,
            cache_read_input_tokens=record.cache_read_input_tokens,
            web_searches=record.web_search_requests,
            cost_usd=str(record.cost_usd),
        )

    def _messages_url(self) -> str:
        base = getattr(self._client, "base_url", None) or DEFAULT_API_URL
        return f"{str(base).rstrip('/')}/v1/messages"

    def _system(self, text: str) -> list[dict[str, Any]]:
        return [{"type": "text", "text": text, "cache_control": {"type": "ephemeral"}}]

    async def _create(self, purpose: str, **params: Any) -> Message:
        model = params["model"]
        attributes: dict[str, tracing.AttributeValue] = {
            "gen_ai.provider.name": "anthropic",
            "gen_ai.operation.name": "chat",
            "gen_ai.request.model": model,
            "gen_ai.request.max_tokens": params.get("max_tokens") or 0,
            "peer.service": "anthropic",
            "trade_agent.purpose": purpose,
            **tracing.http_attributes("POST", self._messages_url()),
        }
        with tracing.span(
            "llm", f"chat {model}", kind=SpanKind.CLIENT, attributes=attributes
        ) as span:
            if self._budget_per_call:
                await self.check_budget()
            await self._fit_budget(purpose, params)
            log.debug(
                "llm.request",
                purpose=purpose,
                model=model,
                max_tokens=params.get("max_tokens"),
                tools=[t["type"] for t in params.get("tools", [])],
                turns=len(params.get("messages", [])),
            )
            retried = False
            while True:
                try:
                    self._inflight = True
                    response: Message = await self._client.messages.create(
                        timeout=self._config.models.timeout_s, **params
                    )
                    break
                except anthropic.APIError as exc:
                    self._inflight = False
                    self._uncertain_charge = self._uncertain_charge or uncertain_api_error(exc)
                    delay = retry_delay(exc, self._clock())
                    if self._cycle_allowance is not None and not retried and delay is not None:
                        retried = True
                        await asyncio.sleep(delay)  # Included in the service's cycle timeout.
                        continue
                    if isinstance(exc, anthropic.APIStatusError):
                        span.set_attribute("http.response.status_code", exc.status_code)
                    raise LlmError(f"{purpose}: {type(exc).__name__}: {exc}") from exc
            span.set_attribute("http.response.status_code", 200)
            await self._record(purpose, model, response)
            return response

    async def structured[T: BaseModel](
        self,
        *,
        purpose: str,
        model: str,
        system: str,
        content: str,
        output: type[T],
        max_tokens: int,
        effort: str | None = None,
    ) -> T:
        output_config: dict[str, Any] = {
            "format": {"type": "json_schema", "schema": anthropic.transform_schema(output)}
        }
        if effort is not None:
            output_config["effort"] = effort
        response = await self._create(
            purpose,
            model=model,
            max_tokens=max_tokens,
            system=self._system(system),
            messages=[{"role": "user", "content": content}],
            output_config=output_config,
        )
        if response.stop_reason != "end_turn":
            raise LlmOutputError(f"{purpose}: stop_reason={response.stop_reason}")
        text = "".join(b.text for b in response.content if b.type == "text")
        try:
            return output.model_validate_json(text)
        except ValidationError as exc:
            raise LlmOutputError(f"{purpose}: saída fora do schema: {exc}") from exc

    async def research(
        self, *, purpose: str, model: str, system: str, content: str, effort: str | None = None
    ) -> ResearchFindings:
        """Research with web search (free text + sources)."""
        web = self._config.web
        tools: list[dict[str, Any]] = [
            {"type": "web_search_20260209", "name": "web_search", "max_uses": web.max_searches}
        ]
        if web.max_fetches:
            tools.append(
                {"type": "web_fetch_20260209", "name": "web_fetch", "max_uses": web.max_fetches}
            )
        extra: dict[str, Any] = {"output_config": {"effort": effort}} if effort else {}
        messages: list[dict[str, Any]] = [{"role": "user", "content": content}]
        blocks: list[Any] = []
        for _ in range(web.max_continuations + 1):
            response = await self._create(
                purpose,
                model=model,
                max_tokens=self._config.models.max_tokens,
                system=self._system(system),
                messages=messages,
                tools=tools,
                **extra,
            )
            blocks.extend(response.content)
            if response.stop_reason != "pause_turn":
                break
            # resumes the server loop: resend the question and the partial answer
            messages = [
                {"role": "user", "content": content},
                {"role": "assistant", "content": blocks},
            ]
        if response.stop_reason not in {"end_turn", "pause_turn"}:
            raise LlmOutputError(f"{purpose}: stop_reason={response.stop_reason}")
        return _findings(blocks)
